import type {Gesto} from '../../config/avatar';
import tiempos from './tiempos.json';

/**
 * Gestos del avatar presentador en "7 días sin comer", atados a las frases de la narración
 * (tiempos.json): cada frase empieza con el gesto indicado, un poco antes de que suene la voz.
 */
const POR_FRASE: Gesto[] = [
  'presentar', // ¿Alguna vez te has preguntado…?
  'explicar', // Tu organismo comenzaría a cambiar…
  'senalar', // Durante las primeras horas…
  'explicar', // Después comienza a recurrir a sus reservas…
  'contar', // Alrededor del segundo día…
  'senalar', // Tu organismo comienza a depender más de la grasa…
  'senalar', // El hígado aumenta la producción…
  'explicar', // Tu cerebro comienza a utilizarlos…
  'leer', // Con el paso de los días…
  'alarma', // Pueden aparecer debilidad, mareos…
  'alarma', // Al séptimo día…
  'cruzar', // La falta de nutrientes…
  'negar', // No existe una respuesta igual…
  'explicar', // El cuerpo humano puede adaptarse…
  'cruzar', // Siete días sin comer pueden representar un riesgo grave…
];

export const GESTOS_AYUNO: {desde: number; gesto: Gesto}[] = [
  {desde: 0, gesto: 'presentar' as Gesto},
  ...tiempos.frases.slice(1).map((f, i) => ({desde: Math.max(0, f.inicio - 0.25), gesto: (POR_FRASE[i + 1] ?? 'explicar') as Gesto})),
  // "…pero eso no significa que sea seguro": niega con la cabeza
  {desde: tiempos.frases[13].inicio + (tiempos.frases[13].fin - tiempos.frases[13].inicio) * 0.62, gesto: 'negar' as Gesto},
  // despedida al terminar la narración
  {desde: tiempos.frases[tiempos.frases.length - 1].fin + 0.4, gesto: 'saludar' as Gesto},
].sort((a, b) => a.desde - b.desde);
